/**
 * Signature Preservation Utilities (Section 9.5)
 * "after any refinement, the server re-attaches the user's original final signature block
 * (everything from the last 'Best regards,' onward) and discards any signature the AI produced."
 */

const SIGNATURE_STARTERS = [
  'best regards,',
  'best regards',
  'warm regards,',
  'warm regards',
  'kind regards,',
  'kind regards',
  'regards,',
  'regards',
  'sincerely,',
  'sincerely',
  'best,',
  'best',
  'cheers,',
  'cheers',
  'thank you,',
  'thanks,',
];

/**
 * Extracts signature block from an email body starting from the last sign-off trigger.
 * Returns { bodyWithoutSig, signature }
 */
export function extractSignature(text) {
  if (!text) return { bodyWithoutSig: '', signature: '' };

  const lines = text.split('\n');
  let lastIndex = -1;

  for (let i = lines.length - 1; i >= 0; i--) {
    const trimmedLower = lines[i].trim().toLowerCase();
    for (const starter of SIGNATURE_STARTERS) {
      if (trimmedLower === starter || trimmedLower.startsWith(starter)) {
        lastIndex = i;
        break;
      }
    }
    if (lastIndex !== -1) break;
  }

  if (lastIndex === -1) {
    return { bodyWithoutSig: text.trim(), signature: '' };
  }

  const bodyWithoutSig = lines.slice(0, lastIndex).join('\n').trim();
  const signature = lines.slice(lastIndex).join('\n').trim();

  return { bodyWithoutSig, signature };
}

/**
 * Strips any signature generated by AI and re-attaches the user's preserved signature block.
 */
export function preserveUserSignature(newAiBody, originalSignature, defaultUserSignature = '') {
  const { bodyWithoutSig } = extractSignature(newAiBody);
  const sigToAttach = originalSignature || defaultUserSignature;

  if (!sigToAttach) {
    return bodyWithoutSig;
  }

  return `${bodyWithoutSig}\n\n${sigToAttach}`;
}
